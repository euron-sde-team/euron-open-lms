#!/usr/bin/env bash
# Write deploy/compose/.env with random, local-only secrets (once; never overwrites a
# value, never prints one). Delete the file to regenerate. An existing file only gains
# the keys added since it was written.
#
# The payment and video secrets are shared by the API and the local stub server
# (apps/stubs), which signs webhooks with them; they are not real Stripe, Razorpay or
# EVS credentials and work nowhere else.
set -euo pipefail
f="$(cd "$(dirname "$0")/.." && pwd)/deploy/compose/.env"
rand() { openssl rand -base64 64 | tr -d '/+=\n' | cut -c1-"$1"; }
# 32 random bytes, standard base64 (TOTP_ENCRYPTION_KEY's format).
key32() { openssl rand -base64 32 | tr -d '\n'; }
umask 077

# key=generator pairs, in file order.
KEYS=(
  "LMS_JWT_SECRET=rand 64"
  "LMS_REFRESH_SECRET=rand 64"
  "LMS_TOTP_ENCRYPTION_KEY=key32"
  "LMS_DEMO_PASSWORD=demo"
  "LMS_STRIPE_SECRET_KEY=stripe"
  "LMS_STRIPE_WEBHOOK_SECRET=whsec"
  "LMS_RAZORPAY_KEY_SECRET=rand 32"
  "LMS_RAZORPAY_WEBHOOK_SECRET=rand 32"
  "LMS_EVS_PLAYBACK_KEY=evs"
  "LMS_EVS_WEBHOOK_SECRET=whsec"
)

value() {
  case "$1" in
    demo) printf 'Demo-%s' "$(rand 12)" ;;
    stripe) printf 'sk_test_local_%s' "$(rand 32)" ;;
    whsec) printf 'whsec_%s' "$(rand 40)" ;;
    evs) printf 'evs_local_%s' "$(rand 40)" ;;
    key32) key32 ;;
    rand*) rand "${1#rand }" ;;
  esac
}

if [[ ! -f "$f" ]]; then
  printf '# Generated by scripts/gen-local-env.sh. Local only; never commit.\n' >"$f"
  fresh=1
else
  fresh=0
fi

added=()
for entry in "${KEYS[@]}"; do
  key="${entry%%=*}"
  gen="${entry#*=}"
  if ! grep -q "^${key}=" "$f"; then
    printf '%s=%s\n' "$key" "$(value "$gen")" >>"$f"
    added+=("$key")
  fi
done

if ((fresh)); then
  echo "wrote deploy/compose/.env"
elif ((${#added[@]})); then
  echo "deploy/compose/.env: added ${added[*]}"
else
  echo "deploy/compose/.env exists (delete it to regenerate)"
fi
